import { createRequire } from 'node:module'
import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
const require = createRequire(import.meta.url)
const { chromium } = require(process.env.BORAI_PLAYWRIGHT || 'playwright')
const browser = await chromium.launch({ headless: true })
const out = new URL('../visual-review/empresas/', import.meta.url)
await mkdir(out, { recursive: true })
try {
  for (const width of [360, 768, 1440]) {
    const context = await browser.newContext({ viewport: { width, height: 900 } })
    const page = await context.newPage()
    page.setDefaultTimeout(15000)
    const errors = [], requests = []
    page.on('pageerror', error => errors.push(error.message))
    page.on('request', request => { if (request.url().includes('/api/')) requests.push(request) })
    await page.goto('http://127.0.0.1:5173')
    await page.locator('#email').fill('cliente@example.test')
    await page.getByRole('button', { name: 'Sou empresa', exact: true }).click()
    async function inspect(name) {
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), `Overflow: ${name}, ${width}`)
      await page.screenshot({ path: new URL(`${name}-${width}.png`, out).pathname.replace(/^\/([A-Z]:)/, '$1'), fullPage: true })
    }
    await inspect('entrada')
    await page.getByRole('button', { name: 'Acessar demonstração pronta' }).click()
    await inspect('visao-geral')
    for (const aba of ['Estabelecimento', 'Fotos', 'Indicadores', 'Plano']) {
      await page.getByRole('navigation', { name: 'Painel empresarial' }).getByRole('button', { name: aba, exact: true }).click()
      await inspect(aba.toLowerCase())
    }
    await page.getByRole('button', { name: 'Voltar ao acesso do cliente' }).click()
    assert.equal(await page.locator('#email').inputValue(), 'cliente@example.test')
    await page.getByRole('button', { name: 'Sou empresa', exact: true }).click()
    await page.getByRole('button', { name: 'Cadastrar minha empresa' }).click()
    await page.getByLabel('Nome do estabelecimento').fill('Café de teste')
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByLabel('Aceita pets', { exact: true }).check()
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.locator('input[type=file]').setInputFiles(new URL('../src/assets/moema-cafe.png', import.meta.url).pathname.replace(/^\/([A-Z]:)/, '$1'))
    await page.getByRole('img', { name: 'moema-cafe.png', exact: true }).waitFor()
    assert.ok((await page.getByRole('img', { name: 'moema-cafe.png', exact: true }).getAttribute('src')).startsWith('blob:'))
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByRole('button', { name: /^Conexão/ }).click()
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByRole('heading', { name: 'Confirmar pagamento', exact: true }).waitFor()
    assert.equal(await page.locator('.be-payment-summary dd').first().textContent(), 'Conexão')
    assert.equal(await page.locator('.be-payment-summary dd').last().textContent(), 'R$ 99,00/mês')
    await page.getByText('Simulação acadêmica — nenhuma cobrança será realizada', { exact: true }).waitFor()
    assert.equal(await page.locator('.be-payment input').count(), 0)
    await inspect('pagamento')
    await page.getByRole('button', { name: 'Voltar aos planos' }).click()
    assert.equal(await page.getByRole('button', { name: /^Conexão/ }).getAttribute('aria-pressed'), 'true')
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByRole('button', { name: 'Confirmar pagamento', exact: true }).click()
    await page.getByRole('heading', { name: 'Bem-vinda ao Boraí Empresas!', exact: true }).waitFor()
    await page.getByText('Seu espaço está pronto para novas conexões.', { exact: true }).waitFor()
    await inspect('boas-vindas')
    await page.getByRole('button', { name: 'Acessar meu painel', exact: true }).click()
    await page.getByRole('heading', { name: 'Café de teste' }).first().waitFor()
    await page.locator('.be-welcome').getByText('Conexão', { exact: true }).waitFor()
    await page.getByRole('navigation').getByRole('button', { name: 'Fotos', exact: true }).click()
    await page.getByRole('button', { name: 'Remover moema-cafe.png', exact: true }).click()
    assert.equal(await page.getByRole('img', { name: 'moema-cafe.png', exact: true }).count(), 0)
    // Alterar a seleção no painel só aplica o plano após a confirmação.
    await page.getByRole('navigation').getByRole('button', { name: 'Plano', exact: true }).click()
    await page.getByRole('button', { name: /^Essencial/ }).click()
    await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByRole('heading', { name: 'Plano Conexão', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Voltar aos planos' }).click()
    await page.getByRole('button', { name: /^Teste grátis por 30 dias/ }).click()
    await page.getByRole('button', { name: 'Iniciar teste grátis', exact: true }).click()
    assert.equal(await page.getByRole('button', { name: 'Confirmar pagamento', exact: true }).count(), 0)
    await page.getByRole('heading', { name: 'Bem-vinda ao Boraí Empresas!', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Acessar meu painel', exact: true }).click()
    await page.locator('.be-welcome').getByText('Teste grátis por 30 dias', { exact: true }).waitFor()
    await page.getByRole('heading', { name: 'Café de teste' }).first().waitFor()
    // O cadastro com teste grátis também segue direto para as boas-vindas.
    await page.getByRole('button', { name: 'Voltar ao acesso do cliente' }).click()
    await page.getByRole('button', { name: 'Sou empresa', exact: true }).click()
    await page.getByRole('button', { name: 'Cadastrar minha empresa' }).click()
    for (let etapa = 0; etapa < 3; etapa++) await page.getByRole('button', { name: 'Continuar' }).click()
    await page.getByRole('button', { name: 'Iniciar teste grátis', exact: true }).click()
    await page.getByRole('heading', { name: 'Bem-vinda ao Boraí Empresas!', exact: true }).waitFor()
    assert.equal(await page.getByRole('button', { name: 'Confirmar pagamento', exact: true }).count(), 0)
    assert.equal(requests.length, 0, 'A demonstração não deve chamar a API')
    assert.equal(await page.evaluate(() => localStorage.length + sessionStorage.length), 0)
    await page.getByRole('button', { name: 'Voltar ao acesso do cliente' }).click()
    // Valida o fluxo do cliente sem autenticar nem escrever no backend real.
    await page.route('**/api/**', async route => {
      const request = route.request()
      if (request.url().endsWith('/users/login')) {
        assert.deepEqual(request.postDataJSON(), { email: 'cliente@example.test', senha: 'senha-de-teste' })
        await route.fulfill({ json: { sessao: { token: 'token-apenas-teste' }, usuario: { id: 'teste', nome: 'Cliente de teste', preferencias: [] } } })
      } else await route.fulfill({ json: { estabelecimentos: [], recomendacoes: [] } })
    })
    await page.route('https://api.open-meteo.com/**', route => route.abort())
    await page.locator('#senha').fill('senha-de-teste')
    await page.getByRole('button', { name: 'Entrar', exact: true }).last().click()
    await page.waitForFunction(() => Boolean(localStorage.getItem('borai_usuario')))
    await page.locator('.login-page').waitFor({ state: 'detached' })
    assert.equal(errors.length, 0, errors.join('\n'))
    console.log(`OK ${width}px: cadastro, pagamento simulado, teste grátis sem pagamento, boas-vindas, painel, fotos, isolamento e login do cliente com API simulada`)
    await context.close()
  }
} finally { await browser.close() }
